# ================================================================================ helpers
def sh(cmd, **kw):
    kw.setdefault('capture_output', True); kw.setdefault('text', True); kw.setdefault('errors', 'replace')
    return subprocess.run(cmd, **kw)

def log(msg):
    print(f'[{dt.datetime.now():%H:%M:%S}] {msg}', flush=True)

def http_ok(url, timeout=2):
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            return r.status == 200
    except Exception:
        return False

def wait_healthy(limit_s=180, poll=0.25):
    """Seconds until GET /healthy answers 200, or None."""
    t0 = time.time()
    while time.time() - t0 < limit_s:
        if http_ok(BASE_URL + '/healthy', 1):
            return time.time() - t0
        time.sleep(poll)
    return None

def pct(sorted_vals, p):
    if not sorted_vals:
        return float('nan')
    return float(sorted_vals[min(len(sorted_vals) - 1, max(0, math.ceil(p * len(sorted_vals)) - 1))])

def prom(query, at=None):
    qs = {'query': query}
    if at: qs['time'] = at
    try:
        with urllib.request.urlopen(PROM_URL + '/api/v1/query?' + urllib.parse.urlencode(qs), timeout=10) as r:
            res = json.load(r)['data']['result']
        return float(res[0]['value'][1]) if res else float('nan')
    except Exception:
        return float('nan')

def num(x, nd=0):
    return 'n/a' if x is None or (isinstance(x, float) and math.isnan(x)) else f'{x:,.{nd}f}'


# ================================================================================ stack control
def reset_stack():
    """Truncates tickets, flushes Redis, restarts the app. Keeps the seed."""
    if EXTERNAL:
        return
    r = sh(['sh', 'reset.sh'], cwd=HERE)
    if r.returncode != 0:
        raise RuntimeError('reset.sh failed: ' + r.stderr[-500:])

def jmeter(plan, jtl, props, heap='-Xms1g -Xmx3g'):
    RESULTS.mkdir(exist_ok=True)
    out = RESULTS / jtl
    if out.exists():
        out.unlink()
    cmd = ['docker', 'run', '--rm', '-e', f'JVM_ARGS={heap}']
    if NETWORK:
        cmd += ['--network', NETWORK]
    cmd += ['-v', f'{HERE}:/work', '-v', f'{HERE}/data:/data', '-w', '/work', JMETER_IMAGE, '-n',
            '-t', f'plans/{plan}', '-l', f'results/{jtl}', '-j', 'results/jmeter.log',
            f'-Jhost={TARGET_HOST}', f'-Jport={TARGET_PORT}'] + [f'-J{k}={v}' for k, v in props.items()]
    r = sh(cmd, env={**os.environ, 'MSYS_NO_PATHCONV': '1'})
    if not out.exists():
        raise RuntimeError(f'JMeter produced no results for {plan}: {r.stdout[-400:]} {r.stderr[-400:]}')
    return out

def read_jtl(path):
    with open(path, encoding='utf-8', errors='replace', newline='') as f:
        return [{'ts': int(r['timeStamp']), 'el': int(r['elapsed']), 'label': r['label'],
                 'ok': r['success'] == 'true', 'threads': int(r['allThreads'] or 0),
                 'msg': (r.get('failureMessage') or r.get('responseMessage') or '')[:140], 'code': r['responseCode']}
                for r in csv.DictReader(f)]

def app_errors(since):
    """ERROR lines in the app log since `since` (epoch s): (count, up to 3 distinct sample lines)."""
    if EXTERNAL:
        return None, []
    r = sh(['docker', 'logs', '--since', dt.datetime.fromtimestamp(since, dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'), APP_CONTAINER])
    lines = [l for l in (r.stdout + r.stderr).splitlines() if ' ERROR ' in l]
    seen, samples = set(), []
    for l in lines:
        k = re.sub(r'[0-9a-f-]{36}|\d+', '#', l)[-120:]
        if k not in seen and len(samples) < 3:
            seen.add(k); samples.append(l[:260])
    return len(lines), samples


