def kafka_offsets():
    """{topic: end offset summed over partitions} for the app's own topics (sos.*, mechanic.*)."""
    out = {}
    try:
        txt = sh(['docker', 'exec', KAFKA_CONTAINER, '/opt/kafka/bin/kafka-get-offsets.sh', '--bootstrap-server', KAFKA_BOOTSTRAP], timeout=40).stdout
    except Exception:
        return out
    for l in txt.splitlines():
        parts = l.rsplit(':', 2)
        if len(parts) == 3 and parts[2].isdigit() and parts[0].startswith(('sos.', 'mechanic.')):
            out[parts[0]] = out.get(parts[0], 0) + int(parts[2])
    return out

def redis_calls(*cmds):
    """Calls so far per Redis command (INFO commandstats); survives FLUSHALL, so use deltas."""
    txt = sh(['docker', 'exec', REDIS_CONTAINER, 'redis-cli', 'INFO', 'commandstats']).stdout
    out = {c: 0 for c in cmds}
    for c in cmds:
        m = re.search(r'cmdstat_%s:calls=(\d+)' % c, txt)
        if m: out[c] = int(m.group(1))
    return out

