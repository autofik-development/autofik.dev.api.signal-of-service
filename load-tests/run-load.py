def scenario_cold(a):
    purpose = ('A freshly started app with empty Redis and no warm connections is hit with load immediately. Measures how long the app takes to answer /healthy, '
               'the latency of the very first request of each kind, and how long until latency settles.')
    runs = []; allser = []; allrows = []
    for i in range(1, a.runs + 1):
        if not EXTERNAL:
            sh(['docker', 'exec', REDIS_CONTAINER, 'redis-cli', 'FLUSHALL']); sh(['docker', 'compose', 'exec', '-T', 'postgres', 'psql', '-U', 'sos', '-d', 'sos', '-c', 'TRUNCATE sos_request CASCADE'], cwd=HERE)
            t_restart = time.time(); sh(['docker', 'restart', APP_CONTAINER])
        ready = wait_healthy(a.ready_limit)
        if ready is None:
            runs.append({'run': i, 'ready_s': None}); continue
        t_ready = time.time()
        mon = Monitor(5); mon.start()
        path = jmeter('stress-stomp.jmx', f'cold-{i}.jtl', {'threads': a.clients, 'ramp': a.ramp, 'duration': a.duration})
        res = mon.finish(); rows = read_jtl(path); an = analyze(rows); t0 = an['t0']
        first = {}
        for r in sorted(rows, key=lambda r: r['ts']):
            first.setdefault(r['label'], r)
        ser = series(rows, 2, t0, f'run{i}')
        late = [w['ping_p95_ms'] for w in ser if w['offset_s'] >= an['duration_s'] * 2 / 3 and isinstance(w['ping_p95_ms'], float) and not math.isnan(w['ping_p95_ms'])]
        target = max(1.5 * (statistics.median(late) if late else 10), 20)
        steady_at = None   # first window that starts a 10 s stretch (5 windows) of ping p95 at or under the target
        vals = [(w['offset_s'], w['ping_p95_ms']) for w in ser]
        for idx, (off, v) in enumerate(vals):
            span = vals[idx:idx + 5]
            if len(span) == 5 and all(not math.isnan(x) and x <= target for _, x in span):
                steady_at = off; break
        runs.append({'run': i, 'ready_s': (t_ready - t_restart) if not EXTERNAL else ready, 'health_poll_s': ready, 'an': an, 'first': first, 'steady_s': steady_at, 'target': target,
                     'err_pct': an['total']['err_pct'], 'first_ts': (min(r['ts'] for r in rows) - t_ready * 1000) / 1000})
        allser += ser; allrows += res
        log(f'cold run {i}: ready after {runs[-1]["ready_s"]:.1f}s, steady at {steady_at}s, errors {an["total"]["err_pct"]:.2f}%')
    good = [r for r in runs if r.get('ready_s') is not None and 'an' in r]
    if not good:
        raise RuntimeError('the app never became healthy')
    write_csv(DATA / 'load-cold-start.csv', allser, SERIES_COLS); write_csv(DATA / 'load-cold-start-resources.csv', allrows, Monitor.COLS)
    med = lambda xs: statistics.median(xs) if xs else float('nan')
    ready_med = med([r['ready_s'] for r in good]); steady_med = med([r['steady_s'] for r in good if r['steady_s'] is not None])
    passed_c = [(f'App ready (/healthy 200) within {COLD_MAX_READY_S} s of restart, every run', len(good) == len(runs) and all(r['ready_s'] <= COLD_MAX_READY_S for r in good)),
                (f'Error rate <= {COLD_MAX_ERR_PCT} % in every run', all(r['err_pct'] <= COLD_MAX_ERR_PCT for r in good)),
                ('Latency settles before the run ends, every run', all(r['steady_s'] is not None for r in good))]
    passed = all(ok for _, ok in passed_c)
    labels = [PING, CREATE, CONNECT, 'GET /api/v1/sos/{id}', 'PATCH /api/v1/mechanics/{id}/location']
    first_rows = [[l] + [num(r['first'][l]['el']) + ('' if r['first'][l]['ok'] else ' (failed)') if l in r['first'] else 'n/a' for r in good] for l in labels]
    run_rows = [[r['run'], num(r['ready_s'], 1), num(r['first_ts'], 1), 'not reached' if r['steady_s'] is None else str(r['steady_s']), num(r['target']), f"{r['err_pct']:.2f}",
                 num(r['an']['labels'].get(PING, {}).get('p95')), num(r['an']['labels'].get(CREATE, {}).get('p95'))] for r in good]
    a0 = good[-1]['an']
    results = ('### Pass criteria\n\n' + table(['Check', 'Result'], [[c, 'pass' if ok else '**FAIL**'] for c, ok in passed_c]) +
               f"\n\nMedian across {len(good)} runs: ready after **{num(ready_med, 1)} s**, latency settled **{num(steady_med)} s** after load began.\n\n### Per run\n\n" +
               table(['Run', 'Restart to /healthy 200 (s)', '/healthy 200 to first sample (s)', 'Time to steady ping p95 (s)', 'Steady target ping p95 (ms)', 'Error %', 'Ping p95 ms', 'Create p95 ms'], run_rows) +
               '\n\n### First request of each kind (ms)\n\n' + table(['Operation'] + [f'Run {r["run"]}' for r in good], first_rows) +
               '\n\n"Steady" = the first 2 s window that starts a 10 s stretch with ping p95 at or under max(1.5 x its median over the last third of the run, 20 ms).\n\n### Last run, per operation\n\n' + label_table(a0))
    pk = peaks(a0['duration_s'] + 30)
    f = [f'Restart to healthy: median {num(ready_med, 1)} s (includes JVM start, Spring context, Hikari warm-up, Kafka admin and Redis listener registration).',
         f'First SOS create took {num(med([r["first"][CREATE]["el"] for r in good if CREATE in r["first"]]))} ms (median) against a steady p50 of {num(a0["labels"].get(CREATE, {}).get("p50"))} ms.',
         f'First ping -> broadcast took {num(med([r["first"][PING]["el"] for r in good if PING in r["first"]]))} ms (median) against a steady p50 of {num(a0["labels"].get(PING, {}).get("p50"))} ms.']
    rec = ['Keep the readiness probe on `/healthy` (it checks the database) and do not route traffic before it returns 200.',
           'If first-request latency matters, warm the JIT and the Hikari pool at startup (a few dummy queries) before reporting ready.']
    save_report('cold-start', 'Load test report: cold start', purpose, passed, [c for c, ok in passed_c if not ok],
                {'Clients': f'{a.clients}, ramp {a.ramp} s, run {a.duration} s', 'Repeats': f'{a.runs} runs, each after `docker restart` of the app and `FLUSHALL` on Redis',
                 'Not reset': 'PostgreSQL data cache, Kafka broker, the JMeter container (starts after /healthy is 200, adds about 2 to 4 s of its own startup)', 'Plan': 'plans/stress-stomp.jmx'},
                results, f, rec, ['reports/data/load-cold-start.csv', 'reports/data/load-cold-start-resources.csv'])
    return passed


