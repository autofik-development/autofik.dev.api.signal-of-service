def scenario_spike(a):
    purpose = (f'A sudden surge: {a.base} clients steady, then {a.spike} more arrive within {a.spike_ramp} s, hold for {a.spike_len - a.spike_ramp} s and leave together. '
               'Shows how far latency climbs, whether requests fail, and how long the service takes to return to normal.')
    reset_stack(); prep_reverse_csvs(); time.sleep(5)
    total = a.spike_at + a.spike_len + a.recover
    path, res, t_start = run_monitored('spike-stomp.jmx', 'spike.jtl', {'base': a.base, 'spike': a.spike, 'spike_ramp': a.spike_ramp, 'spike_at': a.spike_at,
                                                                        'spike_len': a.spike_len, 'duration': total})
    rows = read_jtl(path); an = analyze(rows); t0 = an['t0']; errs = app_errors(t_start)
    ph = lambda lo, hi: [r for r in rows if lo <= (r['ts'] - t0) / 1000 < hi]
    s_end = a.spike_at + a.spike_len
    pre, during, post = ph(0, a.spike_at), ph(a.spike_at, s_end), ph(s_end, 10**9)
    def sub(rs, label=None, skip_create=False):
        return stats([r for r in rs if (label is None or r['label'] == label) and not (skip_create and r['label'] == CREATE)])
    base_p95 = max(5, sub(pre, PING)['p95'] if not math.isnan(sub(pre, PING)['p95']) else 5)
    ser = series(rows, 5, t0); write_csv(DATA / 'load-spike.csv', ser, SERIES_COLS); write_csv(DATA / 'load-spike-resources.csv', res, Monitor.COLS)
    recovery = None
    for w in ser:
        if w['offset_s'] >= s_end:
            win = [r for r in rows if w['offset_s'] <= (r['ts'] - t0) / 1000 < w['offset_s'] + 5 and r['label'] != CREATE]
            st = stats(win)
            if win and st['p95'] <= max(1.5 * base_p95, 20) and st['err'] == 0:
                recovery = w['offset_s'] - s_end; break
    pk = peaks(an['duration_s'] + 30)
    creates_spike = [r for r in during if r['label'] == CREATE]
    passed_c = [('Error rate during the surge <= %.0f %%' % SPIKE_MAX_ERR_PCT, stats(during)['err_pct'] <= SPIKE_MAX_ERR_PCT),
                ('Back to <= 1.5 x baseline ping p95 within %d s of the surge ending' % SPIKE_MAX_RECOVERY_S, recovery is not None and recovery <= SPIKE_MAX_RECOVERY_S),
                ('Every SOS create during the surge succeeded', all(r['ok'] for r in creates_spike) and bool(creates_spike)),
                ('SOS create p95 during the surge <= %d ms' % SPIKE_MAX_CREATE_P95_MS, bool(creates_spike) and sub(during, CREATE)['p95'] <= SPIKE_MAX_CREATE_P95_MS)]
    passed = all(ok for _, ok in passed_c)
    phase_rows = []
    for nm, rs in (('before surge', pre), ('during surge', during), ('after surge', post)):
        st, sp, sc = sub(rs), sub(rs, PING), sub(rs, CREATE)
        phase_rows.append([nm, f"{st['n']:,}", f"{st['n'] / max(1, {'before surge': a.spike_at, 'during surge': a.spike_len, 'after surge': a.recover}[nm]):.0f}", num(sp['p50']), num(sp['p95']), num(sp['p99']), num(sc['p95']), f"{st['err_pct']:.2f}"])
    results = ('### Pass criteria\n\n' + table(['Check', 'Result'], [[c, 'pass' if ok else '**FAIL**'] for c, ok in passed_c]) +
               f"\n\nRecovery time (surge end to first 5 s window back at baseline): **{'not reached' if recovery is None else str(recovery) + ' s'}**. Baseline ping p95 before the surge: {num(base_p95)} ms.\n\n"
               '### By phase\n\n' + table(['Phase', 'Requests', 'RPS', 'Ping p50 ms', 'Ping p95 ms', 'Ping p99 ms', 'Create p95 ms', 'Error %'], phase_rows) +
               '\n\n### Per operation (whole run)\n\n' + label_table(an) + '\n\n### Resources\n\n' + resource_table(res, pk))
    f, r = auto_findings(an, pk, errs, res=res)
    f.insert(0, f"Surge: ping p95 went from {num(sub(pre, PING)['p95'])} ms to {num(sub(during, PING)['p95'])} ms, create p95 from {num(sub(pre, CREATE)['p95'])} ms to {num(sub(during, CREATE)['p95'])} ms; recovery {'not reached' if recovery is None else str(recovery) + ' s'}.")
    save_report('spike', 'Load test report: spike', purpose, passed, [c for c, ok in passed_c if not ok],
                {'Baseline': f'{a.base} clients for the whole run', 'Surge': f'+{a.spike} clients, starting {a.spike_at} s in, ramp {a.spike_ramp} s, hold {a.spike_len - a.spike_ramp} s, leave at {s_end} s',
                 'Run length': f'{total} s ({a.recover} s observation after the surge)', 'Per client': 'create 1 SOS, open 2 WebSockets, then loop: STOMP ping -> broadcast, GET /sos/{id}, PATCH mechanic location, think 0.5-2 s',
                 'Plan': 'plans/spike-stomp.jmx (generated by plans/gen_spike.py)', 'Topics / channels': 'sos.created, sos.notification; /topic/sos/{id}/location; Redis mechanic:loc:*'},
                results, f, r, ['reports/data/load-spike.csv', 'reports/data/load-spike-resources.csv'])
    return passed

def scenario_stress(a):
    purpose = ('Ramp the number of concurrent clients in steps past the expected peak until the service degrades, to find the breaking point, what breaks first, and how it fails. '
               'Each step is a separate run against a freshly reset app.')
    steps = [int(x) for x in a.steps.split(',')]
    allser, allres, step_rows, pk_by, errs_by, fails_by = [], [], [], {}, {}, {}
    base_ping = None; knee = None; broke = None
    for n in steps:
        reset_stack(); time.sleep(10)
        path, res, t_start = run_monitored('stress-stomp.jmx', f'stress-{n}.jtl', {'threads': n, 'ramp': a.ramp, 'duration': a.duration})
        rows = read_jtl(path); an = analyze(rows)
        pk = peaks(an['duration_s'] + 15); errs = app_errors(t_start)
        for r_ in res: r_['step'] = n
        allres += res; allser += series(rows, 5, an['t0'], str(n)); pk_by[n] = pk; errs_by[n] = errs; fails_by[n] = an['fail_msgs']
        ping, cr = an['labels'].get(PING, {}), an['labels'].get(CREATE, {})
        base_ping = base_ping or max(5, ping.get('p95', 5))
        bad = an['total']['err_pct'] > 1.0 or ping.get('p95', 0) > max(2 * base_ping, SLO_PING_P95_MS) or ping.get('p99', 0) > SLO_PING_P99_MS
        if bad and broke is None:
            broke = n
        if not bad and broke is None:
            knee = n
        step_rows.append([n, f"{an['rps']:.0f}", f"{an['stomp_msgs_per_s']:.0f}", f"{num(cr.get('p50'))} / {num(cr.get('p95'))}", num(an['labels'].get(CONNECT, {}).get('p95')),
                          f"{num(ping.get('p50'))} / {num(ping.get('p95'))} / {num(ping.get('p99'))}", f"{an['total']['err']:,} ({an['total']['err_pct']:.1f} %)",
                          f"{num(pk['hikari_active_max'])} / {num(pk['hikari_pending_max'])}", num(pk['tomcat_busy_max']), num(pk['inbound_queued_max']), num(pk['cpu_max_pct'])])
        log(f'step {n}: {an["total"]["err_pct"]:.1f}% errors, ping p95 {ping.get("p95")}')
    write_csv(DATA / 'load-stress.csv', allser, SERIES_COLS); write_csv(DATA / 'load-stress-resources.csv', allres, Monitor.COLS + ['step'])
    passed_c = [(f'First step ({steps[0]} clients) is clean (<=1 % errors, ping p95 within target)', knee is not None),
                (f'Knee at or above the assumed expected peak of {STRESS_MIN_KNEE} clients', knee is not None and knee >= STRESS_MIN_KNEE)]
    passed = all(ok for _, ok in passed_c)
    worst = broke or steps[-1]
    results = ('### Pass criteria\n\n' + table(['Check', 'Result'], [[c, 'pass' if ok else '**FAIL**'] for c, ok in passed_c]) +
               f"\n\n**Knee (last clean step): {knee if knee else 'none'} clients. First degraded step: {broke if broke else 'none reached'}.** A step is degraded when errors exceed 1 %, ping p95 exceeds max(2 x the first step's, {SLO_PING_P95_MS} ms) or ping p99 exceeds {SLO_PING_P99_MS} ms.\n\n"
               '### By step\n\n' + table(['Clients', 'Req/s', 'STOMP msg/s', 'Create p50 / p95 ms', 'WS connect p95 ms', 'Ping p50 / p95 / p99 ms', 'Errors', 'Hikari active / pending (peak)', 'Tomcat busy (peak)', 'STOMP in-queue (peak)', 'App CPU % (peak)'], step_rows) +
               f'\n\n### Resource peaks at the first degraded step ({worst} clients)\n\n' + resource_table([r for r in allres if r.get('step') == worst], pk_by[worst]))
    f = []; rec = []
    if broke:
        sf, sr = auto_findings({'total': {'err': 0, 'n': 1, 'err_pct': 0}, 'labels': {}, 'fail_msgs': fails_by[broke]}, pk_by[broke], errs_by[broke], res=[r_ for r_ in allres if r_.get('step') == broke])
        f.append(f'Degradation starts at {broke} clients; the step before it ({knee}) is the knee.'); f += sf; rec += sr
        if fails_by[broke]:
            f.append('Failure messages at that step: ' + '; '.join(f'`{k}` x{v}' for k, v in list(fails_by[broke].items())[:3]))
    else:
        f.append(f'No step up to {steps[-1]} clients crossed the degradation threshold; the breaking point is higher.')
        rec.append('Add larger steps, or move the injector to a separate machine so the injector is not the limit.')
    f.append('Injector and system under test share one machine, so absolute numbers are pessimistic and the injector may be part of the limit.')
    rec.append('Repeat from a separate Linux host with production-like resources before using these numbers for capacity planning.')
    save_report('stress', 'Load test report: stress', purpose, passed, [c for c, ok in passed_c if not ok],
                {'Steps (clients)': a.steps, 'Per step': f'ramp {a.ramp} s, run {a.duration} s, app reset between steps', 'Per client': 'create 1 SOS, open 2 WebSockets, loop ping -> broadcast / GET / PATCH, think 0.5-2 s',
                 'Plan': 'plans/stress-stomp.jmx', 'Degradation rule': f'errors > 1 % or ping p95 > max(2 x first step, {SLO_PING_P95_MS} ms) or ping p99 > {SLO_PING_P99_MS} ms', 'Topics / channels': 'sos.created, sos.notification; /topic/sos/{id}/location; Redis mechanic:loc:*'},
                results, f, rec, ['reports/data/load-stress.csv', 'reports/data/load-stress-resources.csv'])
    return passed

def scenario_soak(a):
    purpose = ('Steady, moderate load for a long time to expose leaks and drift: heap or thread growth, connections not returned, latency creeping up, Kafka lag or Redis memory growing. '
               f'This run lasted {a.duration} s; the endurance target is 2 to 8 hours (`--duration 7200` and up).')
    reset_stack(); time.sleep(10)
    path, res, t_start = run_monitored('stress-stomp.jmx', 'soak.jtl', {'threads': a.threads, 'ramp': 120, 'duration': a.duration}, interval=15)
    rows = read_jtl(path); an = analyze(rows); errs = app_errors(t_start)
    ser = series(rows, 30, an['t0']); write_csv(DATA / 'load-soak.csv', ser, SERIES_COLS); write_csv(DATA / 'load-soak-resources.csv', res, Monitor.COLS)
    skip = 180   # ignore the ramp and first minutes while pools and JIT settle
    steady = [r for r in res if r['elapsed_s'] > skip] or res
    q = max(1, len(steady) // 4)
    def drift(key):
        v = col(steady, key);
        if len(v) < 2 * q: return None, None, None
        a_, b_ = statistics.median(v[:q]), statistics.median(v[-q:])
        return a_, b_, (100 * (b_ - a_) / a_ if a_ else 0.0)
    ping_rows = [w for w in ser if w['offset_s'] > skip and isinstance(w['ping_p95_ms'], float) and not math.isnan(w['ping_p95_ms'])]
    pq = max(1, len(ping_rows) // 4)
    p_first = statistics.median(w['ping_p95_ms'] for w in ping_rows[:pq]) if ping_rows else float('nan')
    p_last = statistics.median(w['ping_p95_ms'] for w in ping_rows[-pq:]) if ping_rows else float('nan')
    drifts = [('Live heap after GC (MB)', *drift('heap_live_after_gc_mb')), ('(info) Heap used, sampled (MB)', *drift('heap_used_mb')), ('JVM live threads', *drift('live_threads')), ('Hikari active connections', *drift('hikari_active')),
              ('Redis memory (MB)', *drift('redis_used_mb')), ('Kafka consumer lag', *drift('kafka_consumer_lag')),
              ('Ping p95 (ms)', p_first, p_last, (100 * (p_last - p_first) / p_first if p_first and not math.isnan(p_first) else None))]
    def bad(name, a_, b_, d_):
        if d_ is None or a_ is None: return False
        if name.startswith('Ping'): return d_ > 25 and (b_ - a_) > 5
        if name.startswith('Kafka'): return (b_ - a_) > 100
        return d_ > SOAK_MAX_DRIFT_PCT and (b_ - a_) > (5 if 'Hikari' in name or 'threads' in name else 20)
    passed_c = [('Error rate <= 0.5 %', an['total']['err_pct'] <= 0.5)] + [(f'{n}: drift <= {SOAK_MAX_DRIFT_PCT:.0f} % (first vs last quarter of the steady state)', not bad(n, x, y, z)) for n, x, y, z in drifts if not n.startswith('(info)')]
    passed = all(ok for _, ok in passed_c)
    dtab = table(['Signal', 'First quarter (median)', 'Last quarter (median)', 'Drift'], [[n, num(x, 1), num(y, 1), 'n/a' if z is None else f'{z:+.1f} %'] for n, x, y, z in drifts])
    pk = peaks(an['duration_s'] + 30)
    results = ('### Pass criteria\n\n' + table(['Check', 'Result'], [[c, 'pass' if ok else '**FAIL**'] for c, ok in passed_c]) +
               f"\n\n### Drift over the run (first {skip} s excluded)\n\n" + dtab +
               f"\n\n### Totals\n\n{an['total']['n']:,} requests in {an['duration_s']:.0f} s ({an['rps']:.0f}/s), {an['total']['err']} errors.\n\n### Per operation\n\n" + label_table(an) + '\n\n### Resources\n\n' + resource_table(res, pk))
    f, r = auto_findings(an, pk, errs, res=res)
    if a.duration < 7200:
        f.append(f'Short soak: {a.duration} s is not an endurance test. Slow leaks (a few MB per hour) and 1 to 2 hour effects such as expiry sweeps, token or cache churn and connection aging are not covered.')
        r.append('Run `python load-tests/run-load.py soak --duration 7200` (2 h) or longer on a dedicated host before a release.')
    f.append('Each client creates one SOS at the start and then only pings, so ticket churn, bids and status changes are absent from the soak mix; the bidding-window expiry path runs once per ticket.')
