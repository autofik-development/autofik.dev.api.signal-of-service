class Monitor(threading.Thread):
    """Samples the app (Prometheus), Redis, Kafka and the container CPU/memory every `interval` s."""
    COLS = ['timestamp', 'elapsed_s', 'app_cpu_pct', 'heap_used_mb', 'heap_live_after_gc_mb', 'live_threads', 'tomcat_busy', 'hikari_active',
            'hikari_pending', 'stomp_inbound_queued', 'stomp_outbound_queued', 'gc_pause_pct',
            'redis_used_mb', 'redis_clients', 'redis_ops_per_s', 'redis_usec_per_cmd',
            'kafka_sos_msgs_total', 'kafka_msgs_per_s', 'kafka_consumer_lag', 'container_cpu_pct', 'container_mem_mb']

    def __init__(self, interval=10):
        super().__init__(daemon=True)
        self.interval, self.rows, self.stop_evt, self.t0 = interval, [], threading.Event(), time.time()
        self._prev_k, self._prev_c = None, None

    def _exec(self, container, args, timeout=20):
        try:
            return sh(['docker', 'exec', container] + args, timeout=timeout).stdout
        except Exception:
            return ''

    def redis(self):
        if EXTERNAL and not E('REDIS_CONTAINER'):
            return {}
        info = self._exec(REDIS_CONTAINER, ['redis-cli', 'INFO', 'everything'])
        get = lambda k: next((float(l.split(':')[1]) for l in info.splitlines() if l.startswith(k + ':')), float('nan'))
        calls = usec = 0.0
        for l in info.splitlines():
            m = re.match(r'cmdstat_\w+:calls=(\d+),usec=(\d+)', l)
            if m and not l.startswith(('cmdstat_info', 'cmdstat_flushall')):
                calls += int(m.group(1)); usec += int(m.group(2))
        out = {'redis_used_mb': get('used_memory') / 1048576, 'redis_clients': get('connected_clients'),
               'redis_ops_per_s': get('instantaneous_ops_per_sec')}
        if self._prev_c and calls > self._prev_c[0]:
            out['redis_usec_per_cmd'] = (usec - self._prev_c[1]) / (calls - self._prev_c[0])
        self._prev_c = (calls, usec)
        return out

    def kafka(self):
        if EXTERNAL and not E('KAFKA_CONTAINER'):
            return {}
        tool = '/opt/kafka/bin/'
        total = sum(v for k, v in kafka_offsets().items() if k != 'sos.dlq')
        lag = 0
        grp = self._exec(KAFKA_CONTAINER, [tool + 'kafka-consumer-groups.sh', '--bootstrap-server', KAFKA_BOOTSTRAP, '--describe', '--all-groups'], 40)
        for l in grp.splitlines():
            f = l.split()
            if len(f) >= 6 and f[5].isdigit() and (f[1].startswith(('sos.', 'mechanic.'))):
                lag += int(f[5])
        out = {'kafka_sos_msgs_total': total, 'kafka_consumer_lag': lag}
        now = time.time()
        if self._prev_k:
            out['kafka_msgs_per_s'] = (total - self._prev_k[0]) / max(1e-6, now - self._prev_k[1])
        self._prev_k = (total, now)
        return out

    def container(self):
        if EXTERNAL:
            return {}
        try:
            j = json.loads(sh(['docker', 'stats', '--no-stream', '--format', '{{json .}}', APP_CONTAINER], timeout=20).stdout.strip().splitlines()[0])
            mem = j['MemUsage'].split('/')[0].strip()
            mb = float(re.sub(r'[^0-9.]', '', mem)) * (1024 if 'GiB' in mem else 1 if 'MiB' in mem else 1 / 1024)
            return {'container_cpu_pct': float(j['CPUPerc'].rstrip('%')), 'container_mem_mb': mb}
        except Exception:
            return {}

    def sample(self):
        now = time.time()
        row = {'timestamp': dt.datetime.fromtimestamp(now, dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
               'elapsed_s': round(now - self.t0),
               'app_cpu_pct': prom('process_cpu_usage') * 100,
               'heap_used_mb': prom('sum(jvm_memory_used_bytes{area="heap"})') / 1048576,
               'heap_live_after_gc_mb': prom('jvm_gc_live_data_size_bytes') / 1048576,
               'live_threads': prom('jvm_threads_live_threads'), 'tomcat_busy': prom('tomcat_threads_busy_threads'),
               'hikari_active': prom('hikaricp_connections_active'), 'hikari_pending': prom('hikaricp_connections_pending'),
               'stomp_inbound_queued': prom('executor_queued_tasks{name="clientInboundChannelExecutor"}'),
               'stomp_outbound_queued': prom('executor_queued_tasks{name="clientOutboundChannelExecutor"}'),
               'gc_pause_pct': prom('rate(jvm_gc_pause_seconds_sum[30s])') * 100}
        row.update(self.redis()); row.update(self.kafka()); row.update(self.container())
        self.rows.append(row)

    def run(self):
        while not self.stop_evt.is_set():
            t = time.time()
            try:
                self.sample()
            except Exception as e:
                log(f'monitor sample failed: {e}')
            self.stop_evt.wait(max(0.5, self.interval - (time.time() - t)))

    def finish(self):
        self.stop_evt.set(); self.join(timeout=60)
        return self.rows

def col(rows, key):
    return [r[key] for r in rows if isinstance(r.get(key), (int, float)) and not math.isnan(r[key])]

def peaks(window_s):
    """Peak values over the last `window_s` seconds, straight from Prometheus (catches short spikes)."""
    w = f'[{int(window_s) + 5}s]'
    q = {'tomcat_busy_max': f'max_over_time(tomcat_threads_busy_threads{w})',
         'hikari_active_max': f'max_over_time(hikaricp_connections_active{w})',
         'hikari_pending_max': f'max_over_time(hikaricp_connections_pending{w})',
         'inbound_queued_max': f'max_over_time(executor_queued_tasks{{name="clientInboundChannelExecutor"}}{w})',
         'inbound_active_max': f'max_over_time(executor_active_threads{{name="clientInboundChannelExecutor"}}{w})',
         'outbound_queued_max': f'max_over_time(executor_queued_tasks{{name="clientOutboundChannelExecutor"}}{w})',
         'cpu_max_pct': f'100*max_over_time(process_cpu_usage{w})',
         'heap_max_mb': f'max_over_time(sum(jvm_memory_used_bytes{{area="heap"}})[{int(window_s) + 5}s:5s])/1048576',
         'threads_max': f'max_over_time(jvm_threads_live_threads{w})',
         'gc_pause_max_ms': f'1000*max_over_time(jvm_gc_pause_seconds_max{w})'}
    return {k: prom(v) for k, v in q.items()}


# ================================================================================ analysis
def stats(rows):
    el = sorted(r['el'] for r in rows)
    bad = sum(not r['ok'] for r in rows)
    return {'n': len(rows), 'p50': pct(el, .5), 'p95': pct(el, .95), 'p99': pct(el, .99), 'max': el[-1] if el else float('nan'),
            'err': bad, 'err_pct': 100 * bad / len(rows) if rows else 0.0}

def analyze(rows):
    if not rows:
        raise RuntimeError('no samples in the results file')
    t0 = min(r['ts'] for r in rows); t1 = max(r['ts'] + r['el'] for r in rows)
    dur = max(1.0, (t1 - t0) / 1000)
    by = {}
    for r in rows:
        by.setdefault(r['label'], []).append(r)
    a = {'t0': t0, 'duration_s': dur, 'total': stats(rows), 'rps': len(rows) / dur,
         'labels': {k: {**stats(v), 'rps': len(v) / dur} for k, v in sorted(by.items())},
         'fail_msgs': {}}
    for r in rows:
        if not r['ok']:
            k = f"{r['label']}: {r['code']} {r['msg']}"[:150]
            a['fail_msgs'][k] = a['fail_msgs'].get(k, 0) + 1
    a['fail_msgs'] = dict(sorted(a['fail_msgs'].items(), key=lambda kv: -kv[1])[:5])
    pings = by.get(PING, [])
    a['stomp_msgs_per_s'] = 2 * len([r for r in pings if r['ok']]) / dur   # one SEND in, one MESSAGE out per ping
    return a

def series(rows, window=5, t_origin=None, step=''):
    """Per-window time series: concurrency, throughput, latency, errors (all samples), plus ping/create p95."""
    t0 = t_origin if t_origin is not None else min(r['ts'] for r in rows)
    b = {}
    for r in rows:
        b.setdefault((r['ts'] - t0) // (window * 1000), []).append(r)
    out = []
    for k in sorted(b):
        rs = b[k]; s = stats(rs)
        p = sorted(r['el'] for r in rs if r['label'] == PING); c = sorted(r['el'] for r in rs if r['label'] == CREATE)
        out.append({'timestamp': dt.datetime.fromtimestamp((t0 + k * window * 1000) / 1000, dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
                    'offset_s': k * window, 'step': step, 'concurrency': max(r['threads'] for r in rs), 'rps': round(len(rs) / window, 1),
                    'p50_ms': s['p50'], 'p95_ms': s['p95'], 'p99_ms': s['p99'], 'error_rate_pct': round(s['err_pct'], 2),
                    'ping_p95_ms': pct(p, .95), 'create_p95_ms': pct(c, .95)})
    return out

def write_csv(path, rows, cols):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction='ignore')
        w.writeheader()
        for r in rows:
            w.writerow({c: (round(r[c], 2) if isinstance(r.get(c), float) and not math.isnan(r[c]) else ('' if isinstance(r.get(c), float) else r.get(c, ''))) for c in cols})

