FLOW_TARGETS = {   # scenario: (min rate/s of the counted operations, max p95 ms, max error %)
    'create-mix': (50, 2000, 1.0), 'bidding': (100, 1000, 2.0), 'lifecycle': (30, 1000, 1.0), 'geo': (40, 1500, 1.0)}

def psql(sql):
    r = sh(['docker', 'exec', PG_CONTAINER, 'psql', '-U', 'sos', '-d', 'sos', '-At', '-c', sql], timeout=120)
    if r.returncode != 0:
        raise RuntimeError('psql failed: ' + r.stderr[-300:])
    return r.stdout.strip()

def prep_available_mechanics():
    """Bids from an unavailable mechanic are refused, so the bidding plans only use available ones."""
    rows = psql("SELECT id || ',' || round(ST_Y(current_location::geometry)::numeric, 6) || ',' || round(ST_X(current_location::geometry)::numeric, 6) "
                "FROM mechanic WHERE available_status AND current_h3_index IS NOT NULL ORDER BY md5(id::text)")
    (HERE / 'data' / 'mechanics-available.csv').write_text(rows + '\n', encoding='utf-8')
    return rows.count('\n') + 1

def code_counts(rows, label):
    out = {}
    for r in rows:
        if r['label'] == label:
            out[r['code']] = out.get(r['code'], 0) + 1
    return dict(sorted(out.items()))

def flow_report(name, title, purpose, a, an, rows, res, t_start, counted, extra_checks, config, extra_md='', integrity=None):
    """Shared verdict + report for the flow scenarios. `counted` are the labels whose rate and p95 are judged."""
    min_rate, max_p95, max_err = FLOW_TARGETS[name]
    sel = [r for r in rows if r['label'] in counted]
    s = stats(sel); rate = len(sel) / an['duration_s']
    checks = [(f'Throughput of {", ".join(counted)} >= {min_rate}/s (got {rate:.1f}/s)', rate >= min_rate),
              (f'p95 of those <= {max_p95} ms (got {num(s["p95"])} ms)', s['p95'] <= max_p95),
              (f'Error rate (all requests) <= {max_err} % (got {an["total"]["err_pct"]:.2f} %)', an['total']['err_pct'] <= max_err)] + extra_checks
    passed = all(ok for _, ok in checks)
    errs = app_errors(t_start); pk = peaks(an['duration_s'] + 30)
    ser = series(rows, 5); write_csv(DATA / f'load-{name}.csv', ser, SERIES_COLS); write_csv(DATA / f'load-{name}-resources.csv', res, Monitor.COLS)
    md = ('### Pass criteria\n\n' + table(['Check', 'Result'], [[c, 'pass' if ok else '**FAIL**'] for c, ok in checks]) +
          f"\n\n### Totals\n\n{an['total']['n']:,} requests in {an['duration_s']:.0f} s ({an['rps']:.1f}/s), {an['total']['err']} errors.\n\n"
          '### Per operation\n\n' + label_table(an) + '\n\n' + extra_md +
          ('### Data integrity (SQL after the run)\n\n' + table(['Check', 'Value'], integrity) + '\n\n' if integrity else '') +
          '### Resources\n\n' + resource_table(res, pk))
    f, r = auto_findings(an, pk, errs, res=res)
    save_report(name, title, purpose, passed, [c for c, ok in checks if not ok], config, md, f, r,
                [f'reports/data/load-{name}.csv', f'reports/data/load-{name}-resources.csv'])
    return passed

