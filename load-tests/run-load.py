def lag_finding(res):
    lag = col(res, 'kafka_consumer_lag')
    if not lag or max(lag) < 500:
        return None
    idle = [r for r in res if isinstance(r.get('kafka_msgs_per_s'), float) and r['kafka_msgs_per_s'] == 0 and isinstance(r.get('kafka_consumer_lag'), (int, float))]
    msg = f'Kafka consumer lag peaked at {num(max(lag))} messages and was {num(lag[-1])} when the run ended.'
    if len(idle) >= 4 and idle[0]['kafka_consumer_lag'] > idle[-1]['kafka_consumer_lag']:
        rate = (idle[0]['kafka_consumer_lag'] - idle[-1]['kafka_consumer_lag']) / max(1, idle[-1]['elapsed_s'] - idle[0]['elapsed_s'])
        msg += f' With nothing new being produced it drained at about {rate:.1f} messages/s, so the backlog took roughly {num(idle[-1]["kafka_consumer_lag"] / rate / 60, 0)} more minutes to clear. The lag is on `sos.notification`: that consumer makes one OneSignal HTTP call per record (here OneSignal answers 400 to the fake app id), so a burst of SOS fan-out is delivered more slowly than it is produced.'
    return msg

def auto_findings(a, pk, errs, create_label=CREATE, res=None):
    f, rec = [], []
    cr = a['labels'].get(create_label)
    if a['total']['err']:
        f.append(f"{a['total']['err']:,} of {a['total']['n']:,} requests failed ({a['total']['err_pct']:.2f} %). Most common: " + '; '.join(f'`{k}` x{v}' for k, v in list(a['fail_msgs'].items())[:3]))
    if pk.get('hikari_pending_max', 0) and pk['hikari_pending_max'] >= 5:   # a stray 1 or 2 waiting is normal
        f.append(f"DB pool saturated: up to {num(pk['hikari_pending_max'])} threads waited for a connection (pool max {E('DB_POOL_MAX', '20')}).")
        rec.append('Raise `DB_POOL_MAX` (and Postgres `max_connections`) and re-run; if latency does not improve, profile the create transaction instead.')
    if pk.get('tomcat_busy_max', 0) >= 180:
        f.append(f"Tomcat worker threads reached {num(pk['tomcat_busy_max'])} of 200: new HTTP requests and WebSocket upgrades queue behind them.")
        rec.append('Raise `server.tomcat.threads.max` only together with the DB pool; the real fix is to keep requests from holding a thread while they wait on the pool.')
    if pk.get('inbound_queued_max', 0) >= 500:
        f.append(f"STOMP inbound queue reached {num(pk['inbound_queued_max'])} of 1000: location pings are waiting for a worker.")
        rec.append('Raise `websocket.inbound.max-pool-size` / `queue-capacity`, and check that nothing on the ping path blocks (Google ETA call, Postgres write).')
    if cr and cr['p95'] > 1000:
        f.append(f"`POST /api/v1/sos` p95 is {num(cr['p95'])} ms (p50 {num(cr['p50'])} ms), far above the assumed 400 ms target.")
    if errs and errs[0]:
        f.append(f"App log has {errs[0]} ERROR lines, e.g. `{errs[1][0][:200]}`" if errs[1] else f'App log has {errs[0]} ERROR lines.')
    if pk.get('cpu_max_pct', 0) > 85:
        f.append(f"App process CPU peaked at {num(pk['cpu_max_pct'])} % of all host cores: the machine is saturated at this load, and the injector, database, Kafka and Redis share it.")
    lf = lag_finding(res) if res else None
    if lf:
        f.append(lf)
        rec.append('Process `sos.notification` in parallel (listener `concurrency`, or push asynchronously with a bounded executor) so a burst of SOS fan-out does not delay pushes by minutes.')
    if not f:
        f.append('No failures, no pool saturation and no ERROR log lines in this run.')
    if not rec:
        rec.append('No change needed for this scenario at the tested load; raise the load or run on a separate injector host to find the next limit.')
    return f, rec

